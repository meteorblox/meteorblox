import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

// Uses the caller's normal MOVE_HOME and SUI_CONFIG_DIR; never reads wallet keys.
const root = resolve(import.meta.dirname, '../..');
const output = execFileSync(process.env.SUI_BIN ?? 'sui', [
  'move', 'build', '--dump-bytecode-as-base64', '--no-tree-shaking', '--silence-warnings',
], { cwd: root, encoding: 'utf8', env: process.env });
const line = output.split(/\r?\n/).find((line) => line.startsWith('{"modules"'));
if (!line) throw new Error('Build did not return package bytecode');
const artifact = {
  expectedVersion: '13',
  expectedPackage: '0xaebe9d7ea708b5466bf500db575c12e5fb895ef3fcf1b8841e73b25ffebb6928',
  ...JSON.parse(line),
};
writeFileSync(resolve(root, 'web/app/refinery-upgrade-data.ts'),
  '// Generated by scripts/generate-refinery-upgrade.mjs from the reviewed sources.\n' +
  `export const refineryUpgradeData = ${JSON.stringify(artifact)} as const;\n`);

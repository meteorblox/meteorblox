import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const siteRoot = resolve(import.meta.dirname, "..");
const contractRoot = resolve(siteRoot, "../meteorblox");
const sui = resolve(siteRoot, "../sui-cli/sui.exe");
const output = execFileSync(
  sui,
  ["move", "build", "--dump-bytecode-as-base64", "--no-tree-shaking", "--silence-warnings"],
  {
    cwd: contractRoot,
    encoding: "utf8",
    env: {
      ...process.env,
      MOVE_HOME: resolve(contractRoot, ".move-cache"),
      SUI_CONFIG_DIR: resolve(contractRoot, ".sui-config"),
    },
  },
);
const jsonLine = output.split(/\r?\n/).find((line) => line.startsWith('{"modules"'));
if (!jsonLine) throw new Error("Sui build did not return upgrade bytecode JSON");
const data = JSON.parse(jsonLine);
writeFileSync(
  resolve(siteRoot, "app/upgrade-data.ts"),
  `// Generated by scripts/generate-upgrade-data.mjs.\nexport const upgradeData = ${JSON.stringify(data)} as const;\n`,
);

